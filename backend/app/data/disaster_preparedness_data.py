def map_alert_to_disaster_category(alert_type: Optional[str]) -> Optional[str]:
    """
    Maps a weather alert type to a corresponding disaster category.
    Returns None if the alert type does not indicate a disaster.
    """
    if not alert_type:
        return None
    normalized = str(alert_type).strip().lower()
    return ALERT_TYPE_TO_DISASTER_CATEGORY.get(normalized)


def get_all_disaster_categories() -> List[Dict[str, Any]]:
    """
    Returns the list of all supported disaster preparedness categories.
    """
    return list(DISASTER_PREPAREDNESS_REGISTRY.values())


def get_disaster_category_data(category_key: str) -> Optional[Dict[str, Any]]:
    """
    Retrieves the preparedness data for a specific disaster category.
    """
    return DISASTER_PREPAREDNESS_REGISTRY.get(category_key)
